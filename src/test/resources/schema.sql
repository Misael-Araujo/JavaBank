CREATE TABLE user_tb (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complete_name VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL,
    document VARCHAR(14),
    password_hash VARCHAR(100) NOT NULL,
    wallet NUMERIC(19, 2) NOT NULL CHECK (wallet >= 0),
    user_type VARCHAR(20) NOT NULL,
    role VARCHAR(20) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX uk_user_email ON user_tb(email);
CREATE UNIQUE INDEX uk_user_document ON user_tb(document);

CREATE TABLE transaction_tb (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payer_id BIGINT NOT NULL,
    payee_id BIGINT NOT NULL,
    amount NUMERIC(19, 2),
    transfer_date TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL,
    transaction_type VARCHAR(20) NOT NULL,
    CONSTRAINT fk_payer_id_user_id FOREIGN KEY (payer_id) REFERENCES user_tb(id),
    CONSTRAINT fk_payee_id_user_id FOREIGN KEY (payee_id) REFERENCES user_tb(id),
    CONSTRAINT ck_transaction_amount_positive CHECK (amount IS NULL OR amount > 0)
);

CREATE INDEX idx_transaction_payer_date ON transaction_tb(payer_id, transfer_date);
CREATE INDEX idx_transaction_payee_date ON transaction_tb(payee_id, transfer_date);
